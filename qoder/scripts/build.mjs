import { readFile, writeFile, mkdir } from 'node:fs/promises';
const read = file => readFile(new URL(`../${file}`, import.meta.url), 'utf8');
const output = async (file, content) => writeFile(new URL(`../${file}`, import.meta.url), content);
let html = await read('public/index.html');
html = html.replace('data-api-base="/api"', 'data-api-base="/functions/v1/app"')
  .replace('<link rel="stylesheet" href="style.css">', `<style>\n${await read('public/style.css')}\n</style>`)
  .replace('<script src="app.js" defer></script>', `<script>\n${await read('public/app.js')}\n</script>`);
const demo = await readFile(new URL('../public/demo.png', import.meta.url));
html = html.replace('src="demo.png"', `src="data:image/png;base64,${demo.toString('base64')}"`);
await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
await mkdir(new URL('../functions/', import.meta.url), { recursive: true });
await output('dist/index.html', html);
const modules = await Promise.all(['powercontext', 'tracker', 'http'].map(name => read(`src/${name}.js`)));
const bundle = modules.map(code => code.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '')).join('\n');
await output('functions/handler.js', `// Generated by npm run build from src/. Do not edit this file.\n${bundle}\nexport const handler = createHandler(clientConfig({\n  POWERCONTEXT_URL: Deno.env.get('POWERCONTEXT_URL'),\n  POWERCONTEXT_SCOPE_ID: Deno.env.get('POWERCONTEXT_SCOPE_ID'),\n  POWERCONTEXT_AUTH_HEADER: Deno.env.get('POWERCONTEXT_AUTH_HEADER'),\n  POWERCONTEXT_TOKEN: Deno.env.get('POWERCONTEXT_TOKEN'),\n}));\n`);
console.log('Built dist/index.html and self-contained functions/handler.js');
